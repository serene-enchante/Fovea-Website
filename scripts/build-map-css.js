import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const stylesDirectory = new URL('../styles/', import.meta.url);
const outputFile = new URL('../styles/page-maps-tile.bundle.css', import.meta.url);
const generatedHeader = '/* Generated by scripts/build-map-css.js from page-maps-tile.css. */';

export async function renderMapStyleBundle(directory = stylesDirectory) {
    const manifest = await readFile(new URL('page-maps-tile.css', directory), 'utf8');
    const importPattern = /^@import url\('\.\/([^']+)'\);$/gm;
    const imports = [...manifest.matchAll(importPattern)].map((match) => match[1]);
    const remainingManifest = manifest.replace(importPattern, '').trim();

    if (imports.length === 0 || remainingManifest) {
        throw new Error('Map stylesheet manifest must contain only relative @import entries.');
    }

    const partials = await Promise.all(imports.map(async (file) => {
        return (await readFile(new URL(file, directory), 'utf8')).trimEnd();
    }));

    return `${generatedHeader}\n${partials.join('\n\n')}\n`;
}

async function buildMapStyleBundle() {
    const bundle = await renderMapStyleBundle();
    await writeFile(outputFile, bundle);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    await buildMapStyleBundle();
}
